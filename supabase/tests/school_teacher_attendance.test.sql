begin;

create extension if not exists pgtap with schema extensions;

select plan(5);

select ok(
  EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public'
      AND table_name = 'school_attendance_records'
      AND column_name = 'recorded_by_membership_id'
      AND is_nullable = 'NO'
  ),
  'attendance records require the responsible homeroom teacher'
);

select ok(
  pg_get_functiondef('public.school_validate_attendance_record()'::regprocedure)
    LIKE '%NEW.recorded_by_membership_id%',
  'attendance records validate the recorded-by teacher identity'
);

select ok(
  pg_get_functiondef('public.school_validate_attendance_session()'::regprocedure)
    LIKE '%NEW.submitted_at := now()%',
  'attendance submission time is generated by the database'
);

select ok(
  pg_get_functiondef('public.school_validate_attendance_session()'::regprocedure)
    LIKE '%NEW.status <> ''open''%',
  'new attendance sessions must start open'
);

select ok(
  EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename = 'school_attendance_sessions'
      AND policyname = 'school_attendance_sessions_read'
      AND qual LIKE '%school_can_view_attendance_record%'
  ),
  'attendance sessions are visible only through authorized attendance-record access'
);

select * from finish();
rollback;
